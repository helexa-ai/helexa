/** How often the job list is refreshed while any job is unfinished. */
const POLL_MS = 3_000;
const SIDEBAR_KEY = "musicSidebarExpanded";
const COLLAPSED_KEY = "musicCollapsed";

/**
 * `/music` — song and instrumental generation (#402).
 *
 * Generation is asynchronous: a submitted job lives on the server, so the
 * page keeps no state of its own beyond the form. Closing the tab loses
 * nothing; the list is fetched again on return and polled while anything
 * is still queued or rendering.
 *
 * The form is built from what each model advertises in `/v1/models`
 * (duration range, whether it sings, a step limit), so a new music model
 * appears here without a change to this page.
 *
 * Like `/images`: shown to everyone, generated by account holders. A song
 * costs far more GPU time than a chat message, and jobs are listed per
 * account.
 *
 * Past songs are navigated from a sidebar, like chat history: songs filed
 * under a project are listed there, the rest by date, every section
 * collapsible. Projects and song names are kept in this browser; the
 * songs themselves are the server's.
 *
 * The main column is the studio: the form, and beneath it what is
 * happening now — an idea being written, songs rendering, songs made in
 * this visit. A fresh load shows no old song there; one is opened only by
 * picking it from the history.
 */
export default function Music() {
  const { t, i18n } = useTranslation(["music", "chat", "common"]);
  const { status, accountId, token } = useAuth();
  const authed = status === "authed" && !!accountId;
  const owner = accountId ?? "anon";

  const apiKey = useLiveQuery<string | null, undefined>(
    async () => {
      const m = await db.meta.get(CHAT_API_KEY);
      return typeof m?.value === "string" ? m.value : null;
    },
    [],
    undefined,
  );
  useEffect(() => {
    if (!authed || !token || apiKey !== null) return;
    void ensureChatKey(token);
  }, [authed, token, apiKey]);
  const key = apiKey ?? undefined;

  const [models, setModels] = useState<MusicModel[] | null>(null);
  const [modelId, setModelId] = useState("");
  const [prompt, setPrompt] = useState("");
  const [lyrics, setLyrics] = useState("");
  const [duration, setDuration] = useState("");
  const [seed, setSeed] = useState("");
  const [steps, setSteps] = useState("");
  const [advanced, setAdvanced] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [surprising, setSurprising] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [jobs, setJobs] = useState<AudioJob[]>([]);
  // A song opened from the history. Nothing is opened on arrival.
  const [selectedId, setSelectedId] = useState<string | null>(null);
  // Songs submitted since the page loaded; they stay in the studio panel.
  const [sessionIds, setSessionIds] = useState<ReadonlySet<string>>(() => new Set());
  const panelRef = useRef<HTMLElement>(null);

  const projects = useLiveQuery(() => listMusicProjects(owner), [owner], []);
  const tracks = useLiveQuery(() => listMusicTracks(owner), [owner], []);
  const [editingProjectId, setEditingProjectId] = useState<string | null>(null);
  // Phone widths: an off-canvas drawer. Desktop: expanded by default (the
  // history is what the sidebar is for), collapsible to an icon rail.
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const sidebarExpanded =
    useLiveQuery(async () => {
      const m = await db.meta.get(SIDEBAR_KEY);
      return typeof m?.value === "boolean" ? m.value : true;
    }, [], true) ?? true;
  const collapsed = new Set(
    useLiveQuery(async () => {
      const m = await db.meta.get(COLLAPSED_KEY);
      return Array.isArray(m?.value) ? (m.value as string[]) : [];
    }, [], []) ?? [],
  );
  function toggleSection(key: string): void {
    const next = new Set(collapsed);
    if (next.has(key)) next.delete(key);
    else next.add(key);
    void db.meta.put({ key: COLLAPSED_KEY, value: [...next] });
  }

  useEffect(() => {
    let live = true;
    listMusicModels({ apiKey: key })
      .then((ms) => {
        if (!live) return;
        setModels(ms);
        setModelId((cur) => (cur && ms.some((m) => m.id === cur) ? cur : (ms[0]?.id ?? "")));
      })
      .catch(() => live && setModels([]));
    return () => {
      live = false;
    };
  }, [key]);

  const model = models?.find((m) => m.id === modelId);
  const limits = model?.limits;
  const seconds = duration.trim() === "" ? (limits?.default_duration ?? 0) : Number(duration);
  const estimate = estimateTokens(seconds, model?.tokensPerSecond);

  // The list is the server's: fetched on arrival and polled while any job
  // is unfinished. Results are applied from the promise callbacks, so the
  // effect itself never sets state.
  const pending = jobs.some((j) => !isTerminal(j.status));
  useEffect(() => {
    if (!authed || !key) return;
    let live = true;
    const load = (): void => {
      listJobs({ apiKey: key })
        .then((js) => {
          if (!live) return;
          setJobs(js);
          // Filing for songs the server has expired is dead weight.
          void pruneMusicTracks(owner, new Set(js.map((j) => j.id)));
        })
        .catch(() => {
          /* keep the last list; the next tick retries */
        });
    };
    load();
    const id = pending ? setInterval(load, POLL_MS) : undefined;
    return () => {
      live = false;
      if (id) clearInterval(id);
    };
  }, [authed, key, pending, owner]);

  const filing = useMemo(
    () => new Map((tracks ?? []).map((tr) => [tr.jobId, tr.projectId])),
    [tracks],
  );
  const titles = useMemo(
    () => new Map((tracks ?? []).flatMap((tr) => (tr.title ? [[tr.jobId, tr.title] as const] : []))),
    [tracks],
  );
  const groups = useMemo(
    () => groupHistory(jobs, filing, new Set((projects ?? []).map((p) => p.id)), new Date()),
    [jobs, filing, projects],
  );
  const selected = jobs.find((j) => j.id === selectedId);
  function select(id: string): void {
    setSelectedId(id);
    setSidebarOpen(false);
    requestAnimationFrame(() => panelRef.current?.scrollIntoView({ behavior: "smooth", block: "nearest" }));
  }
  // The studio panel: the opened song first, then this visit's songs and
  // anything still rendering from before, newest first.
  const studio = [
    ...(selected ? [selected] : []),
    ...jobs.filter((j) => j.id !== selected?.id && (sessionIds.has(j.id) || !isTerminal(j.status))),
  ].slice(0, 4);

  async function run(): Promise<void> {
    if (!model || blocker) return;
    setError(null);
    setSubmitting(true);
    const parsedSeed = seed.trim() === "" ? undefined : Number(seed.trim());
    const parsedSteps = steps.trim() === "" ? undefined : Number(steps.trim());
    try {
      const job = await submitJob(
        {
          model: model.id,
          prompt: prompt.trim(),
          lyrics: model.limits.vocals ? lyrics.trim() || undefined : undefined,
          duration: duration.trim() === "" ? undefined : clampDuration(Number(duration), {
            vocals: model.limits.vocals,
            minDuration: model.limits.min_duration,
            maxDuration: model.limits.max_duration,
          }),
          seed: Number.isFinite(parsedSeed) ? parsedSeed : undefined,
          steps: Number.isFinite(parsedSteps) ? parsedSteps : undefined,
        },
        { apiKey: key },
      );
      setJobs((js) => [job, ...js.filter((j) => j.id !== job.id)]);
      setSessionIds((ids) => new Set(ids).add(job.id));
      setSelectedId(null);
    } catch (e) {
      setError(e instanceof MusicError ? e.message : t("music:errorGeneric"));
    } finally {
      setSubmitting(false);
    }
  }

  async function onSurprise(): Promise<void> {
    if (!limits || surprising) return;
    setSurprising(true);
    try {
      const { idea } = await surprise(
        {
          vocals: limits.vocals,
          minDuration: limits.min_duration,
          maxDuration: limits.max_duration,
        },
        { apiKey: key },
      );
      setPrompt(idea.prompt);
      setLyrics(idea.lyrics);
      setDuration(String(idea.duration));
      setSeed(String(Math.floor(Math.random() * 2 ** 31)));
    } finally {
      setSurprising(false);
    }
  }

  const blocker = generateBlocker({
    ready: authed && apiKey !== null,
    hasModel: !!model,
    surprising,
    submitting,
    prompt,
    seconds,
    min: limits?.min_duration,
    max: limits?.max_duration,
  });
  // Fields are locked while an idea is being written into them, and while
  // a submission is in flight.
  const locked = submitting || surprising;

  const rowProps = {
    projects: projects ?? [],
    titles,
    filing,
    selectedId: selected?.id,
    onSelect: select,
    owner,
    locale: i18n.language,
    t,
  };

  return (
    <div className="d-flex flex-grow-1" style={{ minHeight: 0 }}>
      {authed ? (
        <>
          {sidebarOpen ? (
            <div className="hx-drawer-backdrop" onClick={() => setSidebarOpen(false)} aria-hidden="true" />
          ) : null}
          <aside
            className={`hx-chat-sidebar hx-music-sidebar ${sidebarOpen ? "open" : ""} ${
              sidebarExpanded ? "expanded" : "rail"
            }`}
            aria-label={t("music:history")}
          >
            <div className="hx-sidebar-actions">
              <button
                type="button"
                className="hx-icon-btn hx-sidebar-action hx-sidebar-expand"
                title={t("music:history")}
                aria-label={t("music:history")}
                aria-expanded={sidebarExpanded}
                onClick={() => void db.meta.put({ key: SIDEBAR_KEY, value: !sidebarExpanded })}
              >
                <FaBarsStaggered size={15} />
              </button>
              <button
                type="button"
                className="hx-icon-btn hx-sidebar-action"
                title={t("chat:newProject")}
                aria-label={t("chat:newProject")}
                onClick={() =>
                  void createMusicProject(owner, t("chat:newProjectName")).then(setEditingProjectId)
                }
              >
                <LuFolderPlus size={17} />
              </button>
            </div>

            {(projects ?? []).map((p) => {
              const songs = groups.byProject.get(p.id) ?? [];
              const open = !collapsed.has(projectKey(p.id));
              return (
                <div key={p.id}>
                  {editingProjectId === p.id ? (
                    <InlineRename
                      initial={p.name}
                      onCommit={(name) => {
                        if (name.trim()) void renameMusicProject(p.id, name.trim());
                        setEditingProjectId(null);
                      }}
                      onCancel={() => setEditingProjectId(null)}
                      t={t}
                    />
                  ) : (
                    <div className="hx-row hx-group-label d-flex align-items-center">
                      <SectionToggle
                        open={open}
                        label={p.name}
                        count={songs.length}
                        onToggle={() => toggleSection(projectKey(p.id))}
                      />
                      <span className="hx-row-actions">
                        <button
                          type="button"
                          className="hx-icon-btn hx-row-btn"
                          title={t("chat:rename")}
                          aria-label={t("chat:rename")}
                          onClick={() => setEditingProjectId(p.id)}
                        >
                          <LuPencil size={13} />
                        </button>
                        <button
                          type="button"
                          className="hx-icon-btn hx-row-btn"
                          title={t("chat:delete")}
                          aria-label={t("chat:delete")}
                          onClick={() => void archiveMusicProject(p.id)}
                        >
                          <LuTrash2 size={13} />
                        </button>
                      </span>
                    </div>
                  )}
                  {open ? songs.map((j) => <TrackRow key={j.id} job={j} {...rowProps} />) : null}
                </div>
              );
            })}

            {groups.byPeriod.map(({ period, jobs: songs }) => {
              const open = !collapsed.has(periodKey(period));
              return (
                <div key={period}>
                  <div className="hx-row hx-group-label d-flex align-items-center">
                    <SectionToggle
                      open={open}
                      label={t(`music:period.${period}`)}
                      count={songs.length}
                      onToggle={() => toggleSection(periodKey(period))}
                    />
                  </div>
                  {open ? songs.map((j) => <TrackRow key={j.id} job={j} {...rowProps} />) : null}
                </div>
              );
            })}

            {jobs.length === 0 ? <p className="hx-row small text-muted mt-2">{t("music:jobsEmpty")}</p> : null}
          </aside>
        </>
      ) : null}
      <main className="app-main container py-4 hx-images hx-music position-relative" style={{ minWidth: 0 }}>
        {authed ? (
          <button
            type="button"
            className="hx-icon-btn hx-sidebar-toggle"
            aria-label={t("music:history")}
            title={t("music:history")}
            onClick={() => setSidebarOpen(true)}
          >
            <FaBarsStaggered size={15} />
          </button>
        ) : null}
        <h1 className="h4 mb-1">{t("music:title")}</h1>
        <p className="text-muted small">{t("music:lead")}</p>

        {!authed ? (
          <div className="hx-image-signin">
            <p>{t("music:signInPrompt")}</p>
            <Link to="/auth?tab=signup" className="hx-btn-primary">
              {t("common:nav.register")}
            </Link>
          </div>
        ) : models === null ? (
          <p className="text-muted small">{t("music:loadingModels")}</p>
        ) : models.length === 0 ? (
          <p className="text-muted small">{t("music:noModels")}</p>
        ) : (
          <form
            className="hx-image-form hx-music-form"
            onSubmit={(e) => {
              e.preventDefault();
              void run();
            }}
          >
            <div className="hx-image-controls">
              <label>
                <span>{t("music:model")}</span>
                <select value={modelId} disabled={locked} onChange={(e) => setModelId(e.target.value)}>
                  {models.map((m) => (
                    <option key={m.id} value={m.id} dir="ltr">
                      {m.id}
                    </option>
                  ))}
                </select>
              </label>
              <button
                type="button"
                className="hx-btn-ghost hx-music-surprise"
                disabled={locked}
                onClick={() => void onSurprise()}
              >
                <FaDice size={13} className={surprising ? "hx-music-spin" : undefined} />{" "}
                {surprising ? t("music:surpriseWorking") : t("music:surprise")}
              </button>
            </div>

            <Notices notices={model?.notices ?? []} />

            <div className={`hx-music-words ${limits?.vocals ? "two" : ""}`}>
              <div className="hx-music-field">
                <label htmlFor="hx-music-style">{t("music:style")}</label>
                <textarea
                  id="hx-music-style"
                  rows={limits?.vocals ? 6 : 3}
                  value={prompt}
                  disabled={locked}
                  placeholder={t("music:stylePlaceholder")}
                  onChange={(e) => setPrompt(e.target.value)}
                />
                <div className="hx-music-tags" role="group" aria-label={t("music:tags")}>
                  {STYLE_TAGS.map((tag) => {
                    const on = hasTag(prompt, tag);
                    return (
                      <button
                        key={tag}
                        type="button"
                        lang="en"
                        className={`hx-music-tag ${on ? "on" : ""}`}
                        aria-pressed={on}
                        disabled={locked}
                        onClick={() => setPrompt((p) => toggleTag(p, tag))}
                      >
                        {tag}
                      </button>
                    );
                  })}
                </div>
              </div>

              {limits?.vocals ? (
                <div className="hx-music-field">
                  <label htmlFor="hx-music-lyrics">{t("music:lyrics")}</label>
                  <textarea
                    id="hx-music-lyrics"
                    className="hx-music-lyrics"
                    rows={10}
                    value={lyrics}
                    disabled={locked}
                    placeholder={t("music:lyricsPlaceholder")}
                    onChange={(e) => setLyrics(e.target.value)}
                  />
                </div>
              ) : null}
            </div>

            <div className="hx-image-controls hx-music-bottom">
              {limits ? (
                <label className="hx-music-length">
                  <span>
                    {t("music:length")} <strong dir="ltr">{clock(seconds)}</strong>
                  </span>
                  <input
                    type="range"
                    min={limits.min_duration}
                    max={limits.max_duration}
                    step={1}
                    value={Number.isFinite(seconds) ? seconds : limits.default_duration}
                    disabled={locked}
                    onChange={(e) => setDuration(e.target.value)}
                  />
                </label>
              ) : null}
              <button
                type="button"
                className="hx-image-advanced"
                aria-expanded={advanced}
                onClick={() => setAdvanced((v) => !v)}
              >
                {t("music:advanced")}
              </button>
              <div className="hx-image-actions">
                {estimate !== undefined ? (
                  <small className="text-muted">
                    {t("music:estimate")}: <span dir="ltr">{estimate.toLocaleString()}</span>
                  </small>
                ) : null}
                <button
                  type="submit"
                  className="hx-btn-primary hx-music-generate"
                  disabled={blocker !== null}
                  aria-describedby={blocker ? "hx-music-blocker" : undefined}
                >
                  <FaArrowUp size={13} /> {t("music:generate")}
                </button>
              </div>
            </div>
            {blocker && blocker.reason !== "submitting" && blocker.reason !== "surprising" ? (
              <p id="hx-music-blocker" className="hx-music-blocker small">
                {blockerText(blocker, t)}
              </p>
            ) : null}

            {advanced ? (
              <div className="hx-image-advanced-panel">
                <label>
                  <span>{t("music:seed")}</span>
                  <input
                    type="text"
                    inputMode="numeric"
                    dir="ltr"
                    value={seed}
                    disabled={locked}
                    placeholder={t("music:seedRandom")}
                    onChange={(e) => setSeed(e.target.value)}
                  />
                  <small>{t("music:seedHint")}</small>
                </label>
                {limits?.max_steps ? (
                  <label>
                    <span>{t("music:steps")}</span>
                    <input
                      type="number"
                      dir="ltr"
                      min={1}
                      max={limits.max_steps}
                      value={steps}
                      disabled={locked}
                      onChange={(e) => setSteps(e.target.value)}
                    />
                  </label>
                ) : null}
              </div>
            ) : null}
          </form>
        )}

        {error ? (
          <div className="alert alert-warning mt-3" role="alert">
            {error}
          </div>
        ) : null}

        {authed ? (
          <section ref={panelRef} className="hx-music-studio" aria-live="polite">
            {surprising ? (
              <div className="hx-music-activity">
                <span className="hx-music-eq" aria-hidden="true">
                  <i />
                  <i />
                  <i />
                  <i />
                </span>
                {t("music:surpriseWorking")}
              </div>
            ) : null}
            {submitting ? (
              <div className="hx-music-activity">
                <span className="hx-music-eq" aria-hidden="true">
                  <i />
                  <i />
                  <i />
                  <i />
                </span>
                {t("music:submitting")}
              </div>
            ) : null}
            {studio.map((j) => (
              <JobCard
                key={j.id}
                job={j}
                title={titles.get(j.id)}
                notices={models?.find((m) => m.id === j.model)?.notices ?? []}
                apiKey={key}
                onChanged={(next) => setJobs((js) => js.map((x) => (x.id === next.id ? next : x)))}
                onClose={j.id === selected?.id ? () => setSelectedId(null) : undefined}
              />
            ))}
          </section>
        ) : null}
      </main>
    </div>
  );
}

/** A collapsible section header: chevron, name, and how many songs it holds. */
function SectionToggle({
  open,
  label,
  count,
  onToggle,
}: {
  open: boolean;
  label: string;
  count: number;
  onToggle: () => void;
}): React.ReactElement {
  return (
    <button type="button" className="hx-group-toggle text-truncate flex-grow-1" aria-expanded={open} onClick={onToggle}>
      {open ? <LuChevronDown size={13} /> : <LuChevronRight size={13} className="hx-flip-rtl" />}
      <span className="text-truncate">{label}</span>
      <span className="hx-group-count" dir="ltr">
        {count}
      </span>
    </button>
  );
}

/** Inline single-field rename editor: Enter/check commits, Escape/x cancels. */
function InlineRename({
  initial,
  onCommit,
  onCancel,
  t,
}: {
  initial: string;
  onCommit: (name: string) => void;
  onCancel: () => void;
  t: (k: string) => string;
}): React.ReactElement {
  const [value, setValue] = useState(initial);
  return (
    <div className="hx-inline-edit d-flex align-items-center gap-1">
      <input
        autoFocus
        value={value}
        onChange={(e) => setValue(e.target.value)}
        onKeyDown={(e) => {
          if (e.key === "Enter") onCommit(value);
          if (e.key === "Escape") onCancel();
        }}
      />
      <button
        type="button"
        className="hx-icon-btn hx-row-btn"
        title={t("chat:rename")}
        aria-label={t("chat:rename")}
        onClick={() => onCommit(value)}
      >
        <LuCheck size={13} />
      </button>
      <button
        type="button"
        className="hx-icon-btn hx-row-btn"
        aria-label={t("chat:cancel")}
        title={t("chat:cancel")}
        onClick={onCancel}
      >
        <LuX size={13} />
      </button>
    </div>
  );
}

/** When a song was made: the time for today's, the date otherwise. */
function when(createdAt: number, locale: string): string {
  const d = new Date(createdAt * 1000);
  const today = new Date().toDateString() === d.toDateString();
  try {
    return today
      ? d.toLocaleTimeString(locale, { hour: "2-digit", minute: "2-digit" })
      : d.toLocaleDateString(locale, { month: "short", day: "numeric" });
  } catch {
    return d.toISOString().slice(0, 10);
  }
}

/** One song in the sidebar: select on click; rename and move-to-project
 * actions on hover (always shown on touch widths). */
function TrackRow({
  job,
  projects,
  titles,
  filing,
  selectedId,
  onSelect,
  owner,
  locale,
  t,
}: {
  job: AudioJob;
  projects: Project[];
  titles: Map<string, string>;
  filing: Map<string, string | null>;
  selectedId?: string;
  onSelect: (id: string) => void;
  owner: string;
  locale: string;
  t: (k: string) => string;
}): React.ReactElement {
  const [editing, setEditing] = useState(false);
  const [menuOpen, setMenuOpen] = useState(false);
  const title = titles.get(job.id) ?? job.prompt ?? job.id;
  const projectId = filing.get(job.id) ?? null;
  const filedHere = projectId !== null && projects.some((p) => p.id === projectId);

  if (editing) {
    return (
      <InlineRename
        initial={title}
        onCommit={(name) => {
          if (name.trim()) void renameMusicTrack(owner, job.id, name.trim());
          setEditing(false);
        }}
        onCancel={() => setEditing(false)}
        t={t}
      />
    );
  }

  const destinations: { id: string | null; name: string }[] = [
    ...(filedHere ? [{ id: null, name: t("chat:unsorted") }] : []),
    ...projects.filter((p) => p.id !== projectId).map((p) => ({ id: p.id as string | null, name: p.name })),
  ];

  return (
    <div className="hx-row position-relative d-flex align-items-center">
      <button
        type="button"
        onClick={() => onSelect(job.id)}
        className={`hx-chat-item hx-music-item flex-grow-1 ${job.id === selectedId ? "active" : ""}`}
        title={title}
      >
        {job.status === "succeeded" ? (
          <span className="hx-music-swatch" style={{ background: coverArt(job.id) }} aria-hidden="true" />
        ) : (
          <span className={`hx-music-dot hx-music-dot-${job.status}`} aria-label={t(`music:status.${job.status}`)} />
        )}
        <span className="text-truncate flex-grow-1">{title}</span>
        <span className="hx-music-when" dir="ltr">
          {when(job.created_at, locale)}
        </span>
      </button>
      <span className="hx-row-actions">
        <button
          type="button"
          className="hx-icon-btn hx-row-btn"
          title={t("chat:rename")}
          aria-label={t("chat:rename")}
          onClick={() => setEditing(true)}
        >
          <LuPencil size={13} />
        </button>
        {destinations.length > 0 ? (
          <button
            type="button"
            className="hx-icon-btn hx-row-btn"
            title={t("chat:moveTo")}
            aria-label={t("chat:moveTo")}
            onClick={() => setMenuOpen((v) => !v)}
          >
            <LuFolderInput size={13} />
          </button>
        ) : null}
      </span>
      {menuOpen ? (
        <>
          <div className="hx-menu-backdrop" onClick={() => setMenuOpen(false)} aria-hidden="true" />
          <div className="hx-move-menu" role="menu">
            {destinations.map((d) => (
              <button
                key={d.id ?? "__dates"}
                type="button"
                role="menuitem"
                className="hx-move-item text-truncate"
                onClick={() => {
                  void moveMusicTrack(owner, job.id, d.id);
                  setMenuOpen(false);
                }}
              >
                {d.name}
              </button>
            ))}
          </div>
        </>
      ) : null}
    </div>
  );
}

/**
 * Notices an upstream licence asks to be passed on, shown beside the one
 * model they apply to. They are the model's, not the service's terms.
 */
function Notices({ notices }: { notices: ModelNotice[] }): React.ReactElement | null {
  if (notices.length === 0) return null;
  return (
    <p className="small text-muted hx-music-notices">
      {notices.map((n, i) => (
        <span key={i}>
          {i > 0 ? " · " : null}
          {n.url ? (
            <a href={n.url} target="_blank" rel="noreferrer">
              {n.text}
            </a>
          ) : (
            n.text
          )}
        </span>
      ))}
    </p>
  );
}

/** The line under the generate button saying what it is waiting for. */
function blockerText(b: Blocker, t: (k: string, o?: Record<string, unknown>) => string): string {
  switch (b.reason) {
    case "preparing":
      return t("music:preparing");
    case "noModel":
      return t("music:noModels");
    case "surprising":
      return t("music:surpriseWorking");
    case "submitting":
      return t("music:submitting");
    case "needStyle":
      return t("music:needStyle");
    case "needLength":
      return t("music:needLength", { min: b.min, max: b.max });
  }
}

/**
 * One song in the studio panel: its cover, what it is, where it is up to,
 * and once it is ready a player. Audio is fetched only when asked for — a
 * finished song is megabytes of FLAC, and fetching on sight would spend
 * the visitor's bandwidth on songs they are only glancing at.
 */
function JobCard({
  job,
  title,
  notices,
  apiKey,
  onChanged,
  onClose,
}: {
  job: AudioJob;
  title?: string;
  notices: ModelNotice[];
  apiKey?: string;
  onChanged: (j: AudioJob) => void;
  /** Present for a song opened from the history: puts it away again. */
  onClose?: () => void;
}): React.ReactElement {
  const { t } = useTranslation(["music", "common"]);
  const [blob, setBlob] = useState<Blob | null>(null);
  const [loading, setLoading] = useState(false);
  const [loadError, setLoadError] = useState(false);

  // A ticking elapsed time while the job is unfinished: like images, the
  // only honest progress signal there is.
  const [now, setNow] = useState(() => Date.now());
  const unfinished = !isTerminal(job.status);
  useEffect(() => {
    if (!unfinished) return;
    const id = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(id);
  }, [unfinished]);
  const since = job.started_at ?? job.created_at;
  // FLAC, or WAV for a job rendered before audio moved to FLAC.
  const storedFormat = job.result?.format ?? "flac";
  const elapsed = Math.max(0, Math.round(now / 1000 - since));

  async function load(): Promise<Blob | null> {
    if (blob) return blob;
    setLoading(true);
    setLoadError(false);
    try {
      const b = await fetchAudio(job.id, { apiKey });
      setBlob(b);
      return b;
    } catch {
      setLoadError(true);
      return null;
    } finally {
      setLoading(false);
    }
  }

  // The content fetch needs the bearer, so a download is a fetched blob
  // handed to a throwaway link rather than a plain href.
  const [downloading, setDownloading] = useState<string | null>(null);
  async function download(format: "stored" | "mp3"): Promise<void> {
    setDownloading(format);
    setLoadError(false);
    try {
      const file = format === "mp3" ? await fetchAudio(job.id, { apiKey, format: "mp3" }) : await load();
      if (!file) return;
      const href = URL.createObjectURL(file);
      const a = document.createElement("a");
      a.href = href;
      a.download = `helexa-${job.id}.${format === "mp3" ? "mp3" : storedFormat}`;
      a.click();
      setTimeout(() => URL.revokeObjectURL(href), 0);
    } catch {
      setLoadError(true);
    } finally {
      setDownloading(null);
    }
  }

  async function cancel(): Promise<void> {
    try {
      onChanged(await cancelJob(job.id, { apiKey }));
    } catch {
      /* the next poll shows the real state */
    }
  }

  const name = title ?? job.prompt ?? job.id;
  return (
    <article className={`hx-music-job hx-music-${job.status}`}>
      <div className="hx-music-cover" style={{ background: coverArt(job.id) }} aria-hidden="true">
        {unfinished ? (
          <span className="hx-music-eq">
            <i />
            <i />
            <i />
            <i />
          </span>
        ) : null}
      </div>
      <div className="hx-music-job-body">
        <header>
          <h2 className="hx-music-title" title={name}>
            {name}
          </h2>
          {onClose ? (
            <button
              type="button"
              className="hx-icon-btn hx-music-close"
              title={t("music:close")}
              aria-label={t("music:close")}
              onClick={onClose}
            >
              <LuX size={15} />
            </button>
          ) : null}
        </header>
        {title && job.prompt ? <p className="hx-music-prompt">{job.prompt}</p> : null}
        <div className="hx-music-meta">
          <span className="hx-music-status">{t(`music:status.${job.status}`)}</span>
          {unfinished ? <span dir="ltr">{clock(elapsed)}</span> : null}
          {job.result ? (
            <span dir="ltr">
              {clock(job.result.duration)} · seed {job.result.seed}
              {job.usage ? ` · ${t("music:cost")} ${Math.round(job.usage.helexa_audio_units)}s` : ""}
            </span>
          ) : null}
          <span className="hx-music-model" dir="ltr">
            {job.model}
          </span>
        </div>
        {job.status === "failed" && job.error?.message ? (
          <p className="small text-warning mb-0">{job.error.message}</p>
        ) : null}
        {job.status === "succeeded" ? (
          <Player
            id={job.id}
            blob={blob}
            loading={loading}
            duration={job.result?.duration ?? 0}
            onLoad={() => void load()}
          />
        ) : null}
        <div className="hx-image-card-actions">
          {unfinished ? (
            <button type="button" className="hx-btn-ghost" onClick={() => void cancel()}>
              <FaStop size={12} /> {t("music:cancel")}
            </button>
          ) : null}
          {job.status === "succeeded" ? (
            <>
              <button
                type="button"
                className="hx-btn-ghost"
                disabled={downloading !== null}
                onClick={() => void download("stored")}
                title={`${t("music:download")} ${storedFormat.toUpperCase()}`}
              >
                <FaDownload size={12} /> {storedFormat.toUpperCase()}
              </button>
              {storedFormat === "flac" ? (
                <button
                  type="button"
                  className="hx-btn-ghost"
                  disabled={downloading !== null}
                  onClick={() => void download("mp3")}
                  title={`${t("music:download")} MP3`}
                >
                  <FaDownload size={12} /> MP3
                </button>
              ) : null}
            </>
          ) : null}
        </div>
        {loadError ? <p className="small text-warning mb-0">{t("music:errorLoad")}</p> : null}
        {job.status === "succeeded" ? <Notices notices={notices} /> : null}
      </div>
    </article>
  );
}

const BARS = 96;

/**
 * Play/pause and a waveform that is also the seek bar. Before the audio
 * has been fetched the waveform is a stand-in shape; pressing play fetches
 * the song, and its real waveform replaces the stand-in once decoded. A
 * browser that cannot decode the format still plays it, over the
 * stand-in.
 */
function Player({
  id,
  blob,
  loading,
  duration,
  onLoad,
}: {
  id: string;
  blob: Blob | null;
  loading: boolean;
  duration: number;
  onLoad: () => void;
}): React.ReactElement {
  const { t } = useTranslation(["music"]);
  const audio = useRef<HTMLAudioElement>(null);
  const url = useMemo(() => (blob ? URL.createObjectURL(blob) : null), [blob]);
  useEffect(() => {
    if (!url) return;
    return () => URL.revokeObjectURL(url);
  }, [url]);

  const [levels, setLevels] = useState<number[] | null>(null);
  useEffect(() => {
    if (!blob) return;
    const Ctx =
      window.AudioContext ?? (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
    if (!Ctx) return;
    let live = true;
    const ctx = new Ctx();
    blob
      .arrayBuffer()
      .then((buf) => ctx.decodeAudioData(buf))
      .then((audioBuf) => {
        if (!live) return;
        const channels = Array.from({ length: audioBuf.numberOfChannels }, (_, c) => audioBuf.getChannelData(c));
        setLevels(peaks(channels, BARS));
      })
      .catch(() => {
        /* keep the stand-in */
      })
      .finally(() => void ctx.close());
    return () => {
      live = false;
    };
  }, [blob]);

  const [playing, setPlaying] = useState(false);
  const [time, setTime] = useState(0);
  const [total, setTotal] = useState(duration);
  // Smooth progress while playing; timeupdate alone fires ~4 times a second.
  useEffect(() => {
    if (!playing) return;
    let frame = 0;
    const tick = (): void => {
      setTime(audio.current?.currentTime ?? 0);
      frame = requestAnimationFrame(tick);
    };
    frame = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(frame);
  }, [playing]);

  // Pressing play before the audio is here fetches it; the element then
  // mounts with autoplay, which is what the press asked for.
  const [wantPlay, setWantPlay] = useState(false);

  function toggle(): void {
    const a = audio.current;
    if (!url) {
      setWantPlay(true);
      onLoad();
      return;
    }
    if (!a) return;
    if (a.paused) void a.play();
    else a.pause();
  }

  function seekTo(fraction: number): void {
    const a = audio.current;
    if (!a || !url) return;
    a.currentTime = Math.min(Math.max(fraction, 0), 1) * (total || duration);
    setTime(a.currentTime);
  }

  const shown = levels ?? placeholderPeaks(id, BARS);
  const length = total || duration;
  const done = length > 0 ? time / length : 0;
  return (
    <div className={`hx-music-player ${levels ? "" : "standin"}`}>
      <button
        type="button"
        className="hx-music-play"
        onClick={toggle}
        disabled={loading}
        aria-label={playing ? t("music:pause") : t("music:play")}
        title={playing ? t("music:pause") : t("music:play")}
      >
        {loading ? <span className="hx-music-spinner" /> : playing ? <FaPause size={14} /> : <FaPlay size={14} />}
      </button>
      <div
        className="hx-music-wave"
        role="slider"
        tabIndex={url ? 0 : -1}
        aria-label={t("music:seek")}
        aria-valuemin={0}
        aria-valuemax={Math.round(length)}
        aria-valuenow={Math.round(time)}
        aria-valuetext={`${clock(time)} / ${clock(length)}`}
        onClick={(e) => {
          const r = e.currentTarget.getBoundingClientRect();
          const x = e.clientX - r.left;
          const rtl = getComputedStyle(e.currentTarget).direction === "rtl";
          seekTo((rtl ? r.width - x : x) / r.width);
        }}
        onKeyDown={(e) => {
          if (e.key === "ArrowRight" || e.key === "ArrowLeft") {
            e.preventDefault();
            const a = audio.current;
            if (!a) return;
            seekTo((a.currentTime + (e.key === "ArrowRight" ? 5 : -5)) / (length || 1));
          }
        }}
      >
        {shown.map((v, i) => (
          <i key={i} className={i / shown.length < done ? "on" : ""} style={{ height: `${12 + v * 88}%` }} />
        ))}
      </div>
      <span className="hx-music-time" dir="ltr">
        {clock(time)} / {clock(length)}
      </span>
      {url ? (
        <audio
          ref={audio}
          src={url}
          preload="auto"
          autoPlay={wantPlay}
          onPlay={() => setPlaying(true)}
          onPause={() => setPlaying(false)}
          onEnded={() => {
            setPlaying(false);
            setTime(0);
          }}
          onTimeUpdate={(e) => setTime(e.currentTarget.currentTime)}
          onLoadedMetadata={(e) => setTotal(e.currentTarget.duration)}
        />
      ) : null}
    </div>
  );
}
