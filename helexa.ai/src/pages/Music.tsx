import { useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { useTranslation } from "react-i18next";
import { useLiveQuery } from "dexie-react-hooks";
import { FaArrowUp, FaDownload, FaPlay, FaStop, FaDice } from "react-icons/fa6";
import { useAuth } from "../auth/context";
import { CHAT_API_KEY, db } from "../data/db";
import { ensureChatKey } from "../lib/ensureChatKey";
import {
  type AudioJob,
  type ModelNotice,
  type MusicModel,
  MusicError,
  cancelJob,
  estimateTokens,
  fetchAudio,
  isTerminal,
  listJobs,
  listMusicModels,
  submitJob,
} from "../lib/musicClient";
import { clampDuration, surprise } from "../lib/musicSurprise";

/** How often the job list is refreshed while any job is unfinished. */
const POLL_MS = 3_000;

/**
 * `/music` — song and instrumental generation (#402).
 *
 * Generation is asynchronous: a submitted job lives on the server, so the
 * page keeps no state of its own beyond the form. Closing the tab loses
 * nothing; the list is fetched again on return and polled while anything
 * is still queued or rendering.
 *
 * The form is built from what each model advertises in `/v1/models`
 * (duration range, whether it sings, a step limit), so a new music model
 * appears here without a change to this page.
 *
 * Like `/images`: shown to everyone, generated by account holders. A song
 * costs far more GPU time than a chat message, and jobs are listed per
 * account.
 */
export default function Music() {
  const { t } = useTranslation(["music", "common"]);
  const { status, accountId, token } = useAuth();
  const authed = status === "authed" && !!accountId;

  const apiKey = useLiveQuery<string | null, undefined>(
    async () => {
      const m = await db.meta.get(CHAT_API_KEY);
      return typeof m?.value === "string" ? m.value : null;
    },
    [],
    undefined,
  );
  useEffect(() => {
    if (!authed || !token || apiKey !== null) return;
    void ensureChatKey(token);
  }, [authed, token, apiKey]);
  const key = apiKey ?? undefined;

  const [models, setModels] = useState<MusicModel[] | null>(null);
  const [modelId, setModelId] = useState("");
  const [prompt, setPrompt] = useState("");
  const [lyrics, setLyrics] = useState("");
  const [duration, setDuration] = useState("");
  const [seed, setSeed] = useState("");
  const [steps, setSteps] = useState("");
  const [advanced, setAdvanced] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [surprising, setSurprising] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [jobs, setJobs] = useState<AudioJob[]>([]);

  useEffect(() => {
    let live = true;
    listMusicModels({ apiKey: key })
      .then((ms) => {
        if (!live) return;
        setModels(ms);
        setModelId((cur) => (cur && ms.some((m) => m.id === cur) ? cur : (ms[0]?.id ?? "")));
      })
      .catch(() => live && setModels([]));
    return () => {
      live = false;
    };
  }, [key]);

  const model = models?.find((m) => m.id === modelId);
  const limits = model?.limits;
  const seconds = duration.trim() === "" ? (limits?.default_duration ?? 0) : Number(duration);
  const estimate = estimateTokens(seconds, model?.tokensPerSecond);

  // The list is the server's: fetched on arrival and polled while any job
  // is unfinished. Results are applied from the promise callbacks, so the
  // effect itself never sets state.
  const pending = jobs.some((j) => !isTerminal(j.status));
  useEffect(() => {
    if (!authed || !key) return;
    let live = true;
    const load = (): void => {
      listJobs({ apiKey: key })
        .then((js) => {
          if (live) setJobs(js);
        })
        .catch(() => {
          /* keep the last list; the next tick retries */
        });
    };
    load();
    const id = pending ? setInterval(load, POLL_MS) : undefined;
    return () => {
      live = false;
      if (id) clearInterval(id);
    };
  }, [authed, key, pending]);

  async function run(): Promise<void> {
    if (!model || !prompt.trim() || submitting) return;
    setError(null);
    setSubmitting(true);
    const parsedSeed = seed.trim() === "" ? undefined : Number(seed.trim());
    const parsedSteps = steps.trim() === "" ? undefined : Number(steps.trim());
    try {
      const job = await submitJob(
        {
          model: model.id,
          prompt: prompt.trim(),
          lyrics: model.limits.vocals ? lyrics.trim() || undefined : undefined,
          duration: duration.trim() === "" ? undefined : clampDuration(Number(duration), {
            vocals: model.limits.vocals,
            minDuration: model.limits.min_duration,
            maxDuration: model.limits.max_duration,
          }),
          seed: Number.isFinite(parsedSeed) ? parsedSeed : undefined,
          steps: Number.isFinite(parsedSteps) ? parsedSteps : undefined,
        },
        { apiKey: key },
      );
      setJobs((js) => [job, ...js.filter((j) => j.id !== job.id)]);
    } catch (e) {
      setError(e instanceof MusicError ? e.message : t("music:errorGeneric"));
    } finally {
      setSubmitting(false);
    }
  }

  async function onSurprise(): Promise<void> {
    if (!limits || surprising) return;
    setSurprising(true);
    try {
      const { idea } = await surprise(
        {
          vocals: limits.vocals,
          minDuration: limits.min_duration,
          maxDuration: limits.max_duration,
        },
        { apiKey: key },
      );
      setPrompt(idea.prompt);
      setLyrics(idea.lyrics);
      setDuration(String(idea.duration));
      setSeed(String(Math.floor(Math.random() * 2 ** 31)));
    } finally {
      setSurprising(false);
    }
  }

  const canGenerate = !!model && !!prompt.trim() && !submitting && authed && apiKey !== null;

  return (
    <main className="app-main container py-4 hx-images hx-music">
      <h1 className="h4 mb-1">{t("music:title")}</h1>
      <p className="text-muted small">{t("music:lead")}</p>

      {!authed ? (
        <div className="hx-image-signin">
          <p>{t("music:signInPrompt")}</p>
          <Link to="/auth?tab=signup" className="hx-btn-primary">
            {t("common:nav.register")}
          </Link>
        </div>
      ) : models === null ? (
        <p className="text-muted small">{t("music:loadingModels")}</p>
      ) : models.length === 0 ? (
        <p className="text-muted small">{t("music:noModels")}</p>
      ) : (
        <form
          className="hx-image-form"
          onSubmit={(e) => {
            e.preventDefault();
            void run();
          }}
        >
          <div className="hx-image-controls">
            <label>
              <span>{t("music:model")}</span>
              <select value={modelId} disabled={submitting} onChange={(e) => setModelId(e.target.value)}>
                {models.map((m) => (
                  <option key={m.id} value={m.id} dir="ltr">
                    {m.id}
                  </option>
                ))}
              </select>
            </label>
            <button
              type="button"
              className="hx-btn-ghost"
              disabled={surprising || submitting}
              onClick={() => void onSurprise()}
            >
              <FaDice size={13} /> {surprising ? t("music:surpriseWorking") : t("music:surprise")}
            </button>
          </div>

          <Notices notices={model?.notices ?? []} />

          <label className="hx-music-field">
            <span>{t("music:style")}</span>
            <textarea
              rows={2}
              value={prompt}
              disabled={submitting}
              placeholder={t("music:stylePlaceholder")}
              onChange={(e) => setPrompt(e.target.value)}
            />
          </label>

          {limits?.vocals ? (
            <label className="hx-music-field">
              <span>{t("music:lyrics")}</span>
              <textarea
                rows={8}
                value={lyrics}
                disabled={submitting}
                placeholder={t("music:lyricsPlaceholder")}
                onChange={(e) => setLyrics(e.target.value)}
              />
            </label>
          ) : null}

          <div className="hx-image-controls">
            <label>
              <span>{t("music:duration")}</span>
              <input
                type="number"
                dir="ltr"
                min={limits?.min_duration}
                max={limits?.max_duration}
                step={1}
                value={duration}
                placeholder={limits ? String(limits.default_duration) : ""}
                disabled={submitting}
                onChange={(e) => setDuration(e.target.value)}
              />
            </label>
            <button
              type="button"
              className="hx-image-advanced"
              aria-expanded={advanced}
              onClick={() => setAdvanced((v) => !v)}
            >
              {t("music:advanced")}
            </button>
            <div className="hx-image-actions">
              {estimate !== undefined ? (
                <small className="text-muted">
                  {t("music:estimate")}: <span dir="ltr">{estimate.toLocaleString()}</span>
                </small>
              ) : null}
              <button type="submit" className="hx-btn-primary" disabled={!canGenerate}>
                <FaArrowUp size={13} /> {t("music:generate")}
              </button>
            </div>
          </div>

          {advanced ? (
            <div className="hx-image-advanced-panel">
              <label>
                <span>{t("music:seed")}</span>
                <input
                  type="text"
                  inputMode="numeric"
                  dir="ltr"
                  value={seed}
                  disabled={submitting}
                  placeholder={t("music:seedRandom")}
                  onChange={(e) => setSeed(e.target.value)}
                />
                <small>{t("music:seedHint")}</small>
              </label>
              {limits?.max_steps ? (
                <label>
                  <span>{t("music:steps")}</span>
                  <input
                    type="number"
                    dir="ltr"
                    min={1}
                    max={limits.max_steps}
                    value={steps}
                    disabled={submitting}
                    onChange={(e) => setSteps(e.target.value)}
                  />
                </label>
              ) : null}
            </div>
          ) : null}
        </form>
      )}

      {authed && apiKey === null ? <p className="text-muted small mt-2">{t("music:preparing")}</p> : null}

      {error ? (
        <div className="alert alert-warning mt-3" role="alert">
          {error}
        </div>
      ) : null}

      {authed ? (
        <section className="hx-music-jobs">
          {jobs.length === 0 ? (
            <p className="text-muted small hx-image-empty">{t("music:jobsEmpty")}</p>
          ) : (
            jobs.map((job) => (
              <JobCard
                key={job.id}
                job={job}
                notices={models?.find((m) => m.id === job.model)?.notices ?? []}
                apiKey={key}
                onChanged={(j) => setJobs((js) => js.map((x) => (x.id === j.id ? j : x)))}
              />
            ))
          )}
        </section>
      ) : null}
    </main>
  );
}

/**
 * One job. Audio is fetched only when asked for — a finished song is
 * megabytes of WAV, and loading every one in the list on arrival would
 * spend the visitor's bandwidth on songs they may never play. The object
 * URL is revoked when the card goes away.
 */
/**
 * Notices an upstream licence asks to be passed on, shown beside the one
 * model they apply to. They are the model's, not the service's terms.
 */
function Notices({ notices }: { notices: ModelNotice[] }): React.ReactElement | null {
  if (notices.length === 0) return null;
  return (
    <p className="small text-muted hx-music-notices">
      {notices.map((n, i) => (
        <span key={i}>
          {i > 0 ? " · " : null}
          {n.url ? (
            <a href={n.url} target="_blank" rel="noreferrer">
              {n.text}
            </a>
          ) : (
            n.text
          )}
        </span>
      ))}
    </p>
  );
}

function JobCard({
  job,
  notices,
  apiKey,
  onChanged,
}: {
  job: AudioJob;
  notices: ModelNotice[];
  apiKey?: string;
  onChanged: (j: AudioJob) => void;
}): React.ReactElement {
  const { t } = useTranslation(["music", "common"]);
  const [blob, setBlob] = useState<Blob | null>(null);
  const [loading, setLoading] = useState(false);
  const [loadError, setLoadError] = useState(false);
  const url = useMemo(() => (blob ? URL.createObjectURL(blob) : null), [blob]);
  useEffect(() => {
    if (!url) return;
    return () => URL.revokeObjectURL(url);
  }, [url]);

  // A ticking elapsed time while the job is unfinished: like images, the
  // only honest progress signal there is.
  const [now, setNow] = useState(() => Date.now());
  const unfinished = !isTerminal(job.status);
  useEffect(() => {
    if (!unfinished) return;
    const id = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(id);
  }, [unfinished]);
  const since = job.started_at ?? job.created_at;
  const elapsed = Math.max(0, Math.round(now / 1000 - since));

  async function load(): Promise<void> {
    setLoading(true);
    setLoadError(false);
    try {
      setBlob(await fetchAudio(job.id, { apiKey }));
    } catch {
      setLoadError(true);
    } finally {
      setLoading(false);
    }
  }

  async function cancel(): Promise<void> {
    try {
      onChanged(await cancelJob(job.id, { apiKey }));
    } catch {
      /* the next poll shows the real state */
    }
  }

  return (
    <article className={`hx-music-job hx-music-${job.status}`}>
      <header>
        <span className="hx-music-status">{t(`music:status.${job.status}`)}</span>
        {unfinished ? (
          <span className="text-muted small" dir="ltr">
            {elapsed}s
          </span>
        ) : null}
        <span className="text-muted small hx-music-model" dir="ltr">
          {job.model}
        </span>
      </header>
      {job.prompt ? <p className="hx-image-prompt">{job.prompt}</p> : null}
      {job.result ? (
        <div className="hx-image-meta" dir="ltr">
          {job.result.duration.toFixed(1)}s · seed {job.result.seed}
          {job.usage ? ` · ${t("music:cost")} ${Math.round(job.usage.helexa_audio_units)}s` : ""}
        </div>
      ) : null}
      {job.status === "failed" && job.error?.message ? (
        <p className="small text-warning">{job.error.message}</p>
      ) : null}
      <div className="hx-image-card-actions">
        {unfinished ? (
          <button type="button" className="hx-btn-ghost" onClick={() => void cancel()}>
            <FaStop size={12} /> {t("music:cancel")}
          </button>
        ) : null}
        {job.status === "succeeded" && !url ? (
          <button type="button" className="hx-btn-ghost" disabled={loading} onClick={() => void load()}>
            <FaPlay size={12} /> {t("music:play")}
          </button>
        ) : null}
        {url ? (
          <>
            <audio controls autoPlay src={url} className="hx-music-player" />
            <a className="hx-btn-ghost" href={url} download={`helexa-${job.id}.wav`}>
              <FaDownload size={12} /> {t("music:download")}
            </a>
          </>
        ) : null}
      </div>
      {loadError ? <p className="small text-warning">{t("music:errorLoad")}</p> : null}
      {job.status === "succeeded" ? <Notices notices={notices} /> : null}
    </article>
  );
}
